#!/usr/bin/env node
/**
 * Derives the admin dashboard's Bible STRUCTURE table -- for each of the
 * 66 books, its id, English name, and the verse count of each chapter.
 *
 * ---------------------------------------------------------------------
 * WHY THE ADMIN NEEDS THIS, AND WHY IT IS ONLY STRUCTURE
 * ---------------------------------------------------------------------
 * M5 lets a content admin curate the Verse of the Day pool, and the pool
 * must only ever contain references that actually exist -- "Psalm 151:1"
 * or "John 3:99" in the pool would mean a day on which the app falls back
 * instead of showing the verse the church chose. Catching that needs the
 * verse counts, so they are derived from the bundled corpus rather than
 * typed from memory.
 *
 * NO SCRIPTURE TEXT IS COPIED. The generated file is ~1,255 numbers and
 * 66 names: about 6 KB, versus 8 MB for the corpus. The admin dashboard
 * never renders a verse -- it renders a REFERENCE and says where it came
 * from -- which is exactly why the M5 resolver splits "which verse" from
 * "what it says" (see mobile/src/features/daily-verses/votdResolver.ts).
 *
 * The English book names come from the app's own book table, so the two
 * cannot drift into naming the same book differently.
 *
 * Regenerate after any Bible import:
 *   node scripts/derive-bible-structure.mjs
 * Verify it is current (CI / pre-commit):
 *   node scripts/derive-bible-structure.mjs --check
 *
 * mobile/src/features/daily-verses/__tests__/bibleStructure.test.ts
 * re-derives the same table from the corpus and fails if this file is
 * stale -- the guard lives on the mobile side because that is where the
 * corpus is.
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const CORPUS = resolve(REPO, 'mobile/src/features/bible/data/web-en.json');
const BOOKS = resolve(REPO, 'mobile/src/features/bible/books.ts');
const OUT = resolve(REPO, 'admin/src/features/daily-verses/bibleStructure.ts');

/**
 * Pulls id/name/order out of the app's book table by reading its source.
 *
 * Parsing TypeScript with a regular expression is normally a bad idea; it
 * is acceptable here because the alternative is a build step for a script
 * that runs by hand, the shape is a literal array of object literals, and
 * a failure is loud -- the count assertion below refuses to write a file
 * derived from a partial parse.
 */
function readBooks() {
  const source = readFileSync(BOOKS, 'utf8');
  const books = [];
  const entry =
    /id:\s*'([^']+)',\s*\n\s*name:\s*'([^']+)',[\s\S]*?order:\s*(\d+),\s*\n\s*chapterCount:\s*(\d+),/g;
  let match;
  while ((match = entry.exec(source)) !== null) {
    books.push({
      id: match[1],
      name: match[2],
      order: Number(match[3]),
      chapterCount: Number(match[4]),
    });
  }
  if (books.length !== 66) {
    throw new Error(`Parsed ${books.length} books from ${BOOKS}, expected 66.`);
  }
  return books.sort((a, b) => a.order - b.order);
}

const corpus = JSON.parse(readFileSync(CORPUS, 'utf8'));
const books = readBooks();

let totalVerses = 0;
const entries = books.map((book) => {
  const chapters = corpus[String(book.order)];
  if (!chapters)
    throw new Error(`No corpus data for book order ${book.order} (${book.name}).`);
  const counts = [];
  for (let chapter = 1; chapter <= book.chapterCount; chapter += 1) {
    const verses = chapters[String(chapter)];
    if (!Array.isArray(verses) || verses.length === 0) {
      throw new Error(`No verses for ${book.name} ${chapter}.`);
    }
    counts.push(verses.length);
    totalVerses += verses.length;
  }
  return { ...book, counts };
});

const rows = entries
  .map(
    (book) =>
      `  { id: '${book.id}', name: '${book.name.replace(/'/g, "\\'")}', order: ${book.order}, verseCounts: [${book.counts.join(', ')}] },`
  )
  .join('\n');

const generated = `/**
 * GENERATED by scripts/derive-bible-structure.mjs -- do not edit by hand.
 *
 * The 66 books, their English names, and the verse count of every
 * chapter, derived from the English corpus bundled in the mobile app.
 *
 * STRUCTURE ONLY -- no verse text. The admin dashboard validates and
 * previews REFERENCES; the words themselves live in the app (see that
 * script's header for why, and for how this file is kept from going
 * stale).
 *
 * Regenerate:  node scripts/derive-bible-structure.mjs
 * Verify:      node scripts/derive-bible-structure.mjs --check
 */

export interface BibleBookStructure {
  /** Canonical slug -- matches mobile/src/features/bible/books.ts. */
  id: string;
  /** English display name. The admin dashboard is English-only. */
  name: string;
  /** 1-66, canonical Protestant-canon order. */
  order: number;
  /** verseCounts[n - 1] is the number of verses in chapter n. */
  verseCounts: number[];
}

export const BIBLE_STRUCTURE: readonly BibleBookStructure[] = [
${rows}
];

const BY_ID = new Map(BIBLE_STRUCTURE.map((book) => [book.id, book]));

export function bookStructureById(bookId: string): BibleBookStructure | undefined {
  return BY_ID.get(bookId);
}

/** How many verses a chapter has, or 0 if the book or chapter does not exist. */
export function verseCountFor(bookId: string, chapter: number): number {
  const book = BY_ID.get(bookId);
  if (!book) return 0;
  if (!Number.isInteger(chapter) || chapter < 1 || chapter > book.verseCounts.length) return 0;
  return book.verseCounts[chapter - 1] ?? 0;
}

/** True only for a reference that exists in the canon. */
export function referenceExists(bookId: string, chapter: number, verse: number): boolean {
  const count = verseCountFor(bookId, chapter);
  return count > 0 && Number.isInteger(verse) && verse >= 1 && verse <= count;
}
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(OUT, 'utf8');
  if (current !== generated) {
    console.error(`\n${OUT} is STALE.\nRun: node scripts/derive-bible-structure.mjs\n`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
  process.exit(0);
}

writeFileSync(OUT, generated);

console.log('');
console.log('Bible structure derivation');
console.log(`  books            ${entries.length}`);
console.log(`  chapters         ${entries.reduce((n, b) => n + b.counts.length, 0)}`);
console.log(`  verses counted   ${totalVerses}`);
console.log(`  written          ${OUT}`);
console.log('');
