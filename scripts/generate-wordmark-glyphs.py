#!/usr/bin/env python3
"""
Derives the opening animation's MARANATHA glyph outlines from the bundled
Noto Serif SemiBold, so the wordmark is vector data rather than live text.

WHY OUTLINES AND NOT <Text>
The opening is drawn by react-native-svg, whose <Text> has no way to
measure a string (no getComputedTextLength / getStartPositionOfChar) and
needs the custom font to be registered before it can draw anything. The
opening starts on the first JavaScript frame -- before fonts have loaded --
so the letters are shipped as path data. They are exactly the shapes the
approved animation drew: the approved harness embedded these same font
bytes (asserted by hash below), at 16 units, weight 600.

Usage:
    python3 scripts/generate-wordmark-glyphs.py            # rewrite the module
    python3 scripts/generate-wordmark-glyphs.py --check    # fail if it is stale

Requires fontTools (pip install fonttools). Idempotent.
"""
import hashlib
import sys
from pathlib import Path

try:
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.ttLib import TTFont
except ImportError:
    sys.exit("This script needs fontTools:  pip install fonttools")

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "mobile/assets/fonts/NotoSerif-SemiBold.ttf"
OUT = ROOT / "mobile/src/features/opening/engine/wordmarkGlyphs.ts"

EXPECTED_SHA256 = "9dd0d841482659fd730fbff4167f105248ce988dae26aabbb78abf1d3d838828"
WORD = "MARANATHA"
SIZE = 16.0  # the approved wordmark's font size, in scene units


def fmt(v: float) -> str:
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def build() -> str:
    data = FONT.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != EXPECTED_SHA256:
        sys.exit(
            "NotoSerif-SemiBold.ttf has changed.\n"
            f"  expected sha256 {EXPECTED_SHA256}\n  found    sha256 {actual}\n"
            "Update EXPECTED_SHA256 deliberately and regenerate."
        )
    font = TTFont(str(FONT))
    upm = font["head"].unitsPerEm
    scale = SIZE / upm
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()
    hmtx = font["hmtx"]

    lines = []
    for ch in sorted(set(WORD), key=WORD.index):
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyph_set, ntos=fmt)
        # font units are y-up; SVG is y-down, so flip y while scaling.
        glyph_set[name].draw(TransformPen(pen, (scale, 0, 0, -scale, 0, 0)))
        advance = hmtx[name][0] * scale
        lines.append(
            f"  {ch}: {{\n    advance: {fmt(advance)},\n    d: '{pen.getCommands()}',\n  }},"
        )

    body = "\n".join(lines)
    return f"""/**
 * GENERATED by scripts/generate-wordmark-glyphs.py -- do not edit by hand.
 *
 * The outlines of the letters in MARANATHA, taken from the bundled
 * Noto Serif SemiBold (SIL OFL 1.1, see assets/fonts/OFL-NotoSerif.txt)
 * at {fmt(SIZE)} scene units, with the baseline at y = 0 and the glyph
 * origin at x = 0. `advance` is the glyph's advance width in the same
 * units.
 *
 * Source font sha256 {EXPECTED_SHA256}
 */
export const WORDMARK_GLYPHS: Record<string, {{ advance: number; d: string }}> = {{
{body}
}};
"""


def main() -> None:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale; run scripts/generate-wordmark-glyphs.py")
        print(f"  ok  {OUT.relative_to(ROOT)}")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"  wrote {OUT.relative_to(ROOT)}  ({len(text)} bytes)")


if __name__ == "__main__":
    main()
